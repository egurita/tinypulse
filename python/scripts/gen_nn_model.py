"""Quantize a trained SpecCNN fold to INT8 and export it to firmware/gen/nn_model.[ch].

The deployed model is the LOSO fold whose held-out subject is S5, so every firmware /
emulator / SIL demo on S5 data runs on a subject the model never saw. Activation
ranges are calibrated on that fold's TRAINING subjects only.

Usage:  uv run python python/scripts/gen_nn_model.py [S5]
"""

import sys

import numpy as np
import torch

from ppg_hr import features
from ppg_hr.data import REPO_ROOT, SUBJECTS
from ppg_hr.nn import SpecCNN, spec_input
from ppg_hr.quant import REQ_SHIFT, QModel, quantize

MODELS = REPO_ROOT / "models" / "stage4" / "spec"
OUT = REPO_ROOT / "firmware" / "gen"


def training_subjects(test_sid):
    i = SUBJECTS.index(test_sid)
    val = SUBJECTS[(i + 1) % len(SUBJECTS)]
    return [s for s in SUBJECTS if s not in (test_sid, val)]


def load_fold(test_sid) -> SpecCNN:
    m = SpecCNN()
    m.load_state_dict(torch.load(MODELS / f"fold_{test_sid}.pt"))
    return m.eval()


def quantized_fold(test_sid, n_calib=20000, seed=0) -> QModel:
    x = np.concatenate([spec_input(features.load(s)["spec"]) for s in training_subjects(test_sid)])
    idx = np.random.default_rng(seed).choice(len(x), min(n_calib, len(x)), replace=False)
    return quantize(load_fold(test_sid), x[np.sort(idx)])


def save_npz(q: QModel, path):
    d = {"logit_scale": q.logit_scale, "l0": q.l0, "ls": q.ls}
    for i, L in enumerate(q.layers):
        d.update({f"w{i}": L.w, f"b{i}": L.b, f"m{i}": L.m0, f"d{i}": L.dilation})
    np.savez(path, **d)


def load_npz(path) -> QModel:
    from ppg_hr.quant import QLayer
    z = np.load(path)
    q = QModel(logit_scale=float(z["logit_scale"]), l0=int(z["l0"]), ls=int(z["ls"]))
    for i in range(4):
        q.layers.append(QLayer(z[f"w{i}"], z[f"b{i}"], int(z[f"d{i}"]), z[f"m{i}"], i < 3))
    return q


def arr(ctype, name, v, per=16):
    v = [str(int(x)) for x in np.ravel(v)]
    rows = ",\n    ".join(", ".join(v[i:i + per]) for i in range(0, len(v), per))
    return f"const {ctype} {name}[{len(v)}] = {{\n    {rows}\n}};\n"


def main():
    sid = sys.argv[1] if len(sys.argv) > 1 else "S5"
    q = quantized_fold(sid)
    save_npz(q, MODELS / f"qmodel_{sid}.npz")
    L = q.layers
    ch, k = L[0].w.shape[0], L[0].w.shape[2]
    (OUT / "nn_model.h").write_text(f"""/* GENERATED by python/scripts/gen_nn_model.py (LOSO fold, held-out {sid}): do not edit. */
#ifndef NN_MODEL_H
#define NN_MODEL_H
#include <stdint.h>
#define NN_CH        {ch}
#define NN_K         {k}
#define NN_D1        {L[0].dilation}
#define NN_D2        {L[1].dilation}
#define NN_D3        {L[2].dilation}
#define NN_REQ_SHIFT {REQ_SHIFT}
#define NN_L0        {q.l0}LL      /* logit -> log2 Q16 multiplier (>> NN_LS) */
#define NN_LS        {q.ls}
""" + "".join(f"extern const int8_t nn_w{i + 1}[{L[i].w.size}];\nextern const int32_t nn_b{i + 1}[{L[i].b.size}];\n"
              f"extern const int32_t nn_m{i + 1}[{L[i].m0.size}];\n" for i in range(3))
        + f"extern const int8_t nn_wh[{L[3].w.size}];\nextern const int32_t nn_bh[{L[3].b.size}];\n#endif\n")
    body = f"/* GENERATED (held-out {sid}). */\n#include \"nn_model.h\"\n\n"
    for i in range(3):
        body += arr("int8_t", f"nn_w{i + 1}", L[i].w) + arr("int32_t", f"nn_b{i + 1}", L[i].b) + arr("int32_t", f"nn_m{i + 1}", L[i].m0)
    body += arr("int8_t", "nn_wh", L[3].w) + arr("int32_t", "nn_bh", L[3].b)
    (OUT / "nn_model.c").write_text(body)
    n_w = sum(l.w.size for l in L)
    print(f"exported fold {sid}: {n_w} int8 weights, {sum(l.b.size + l.m0.size for l in L)} int32 params, "
          f"logit LSB {q.logit_scale:.4g} nats")


if __name__ == "__main__":
    main()
