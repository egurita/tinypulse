"""Embed a real-data segment in the firmware image for the emulator benchmark.

Writes firmware/gen/test_vector.{c,h}: 120 s of held-out subject S5 (rest -> stairs),
as the integer samples the sensors would deliver, plus the HR bins the host build of
the same C code produces (the emulated MCU must reproduce them bit-exactly).

Usage:  uv run python python/scripts/gen_test_vector.py
"""

import json

import numpy as np

from ppg_hr import firmware as fw
from ppg_hr.data import FS_PPG, HR_SHIFT_S, REPO_ROOT, activity_runs, load_subject
from ppg_hr.pipeline import acc_counts, ppg_counts

SID, SECONDS, LEAD_S = "S5", 120, 60      # start 60 s before the stairs begin
OUT = REPO_ROOT / "firmware" / "gen"


def main():
    s = load_subject(SID)
    stairs_start = next(a for act, a, b in activity_runs(s.activity) if act == 2)
    hop = HR_SHIFT_S * FS_PPG
    start = int((stairs_start - LEAD_S) * FS_PPG) // hop * hop     # align with reference windows
    n = SECONDS * FS_PPG
    ppg = ppg_counts(s)[start:start + n].astype(np.uint32)
    acc = acc_counts(s)[start // 2:(start + n) // 2]

    # Expected output: the host build of the same firmware code on the same segment.
    bins = fw.run_counts(ppg, acc, 64, fw.MODE_DSP)
    bins_nn = fw.run_counts(ppg, acc, 64, fw.MODE_NN)
    k = len(bins)
    assert len(bins_nn) == k

    def arr(ctype, name, v, per=12):
        v = [str(int(x)) for x in np.ravel(v)]
        rows = ",\n    ".join(", ".join(v[i:i + per]) for i in range(0, len(v), per))
        return f"const {ctype} {name}[{len(v)}] = {{\n    {rows}\n}};\n"

    (OUT / "test_vector.h").write_text(f"""/* GENERATED by python/scripts/gen_test_vector.py: do not edit. */
#ifndef TEST_VECTOR_H
#define TEST_VECTOR_H
#include <stdint.h>
#define TV_N_PPG {n}
#define TV_N_EXPECTED {k}
extern const uint32_t tv_ppg[TV_N_PPG];
extern const int16_t  tv_acc[TV_N_PPG / 2 * 3];
extern const uint16_t tv_expected_bins[TV_N_EXPECTED];      /* DSP mode */
extern const uint16_t tv_expected_bins_nn[TV_N_EXPECTED];   /* INT8 NN mode */
#endif
""")
    (OUT / "test_vector.c").write_text(
        f"/* GENERATED: {SID}, samples {start}..{start + n} ({SECONDS} s, rest -> stairs). */\n"
        '#include "test_vector.h"\n\n'
        + arr("uint32_t", "tv_ppg", ppg) + arr("int16_t", "tv_acc", acc)
        + arr("uint16_t", "tv_expected_bins", bins) + arr("uint16_t", "tv_expected_bins_nn", bins_nn))
    meta = {"subject": SID, "start_sample": start, "first_ref_window": start // hop,
            "n_samples": n, "expected_bins": bins.tolist(), "expected_bins_nn": bins_nn.tolist()}
    (OUT / "test_vector.json").write_text(json.dumps(meta))
    print(f"wrote test vector: {SID} samples {start}..{start + n}, {k} expected estimates")


if __name__ == "__main__":
    main()
