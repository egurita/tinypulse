"""Generate firmware/gen/hr_tables.{h,c}: constant tables shared by Python and C.

Everything numeric the firmware needs is derived here from the Python reference,
so there is one source of truth:
  - bandpass biquad coefficients (Q29)       from ppg_hr.dsp.bandpass_sos
  - Hann window (Q15, 512)                   = np.hanning(512), as in ppg_hr.dsp.spectrum
  - FFT twiddles cos/sin (Q31, NFFT/2)
  - log2 mantissa table (Q16, 257 entries)   for the fixed-point HMM tracker

Usage:  uv run python python/scripts/gen_firmware_tables.py
"""

import numpy as np

from ppg_hr.data import FS_PPG, HR_WINDOW_S, REPO_ROOT
from ppg_hr.dsp import bandpass_sos
from ppg_hr.pipeline import NFFT

OUT = REPO_ROOT / "firmware" / "gen"
WIN = HR_WINDOW_S * FS_PPG
Q29, Q31, Q15, Q16 = 1 << 29, (1 << 31) - 1, (1 << 15) - 1, 1 << 16
LOG2_TABLE_BITS = 8


def q(x, scale):
    return np.round(np.asarray(x) * scale).astype(np.int64)


def c_array(ctype, name, values, per_line=8):
    vals = [str(int(v)) for v in np.ravel(values)]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def main(out=OUT):
    out.mkdir(parents=True, exist_ok=True)
    sos = bandpass_sos(FS_PPG)
    # Per section: b0 b1 b2 a1 a2 (a0 = 1 is implicit).
    coef = q(sos[:, [0, 1, 2, 4, 5]], Q29)
    assert np.abs(coef).max() < 2**31, "coefficient overflow: use a smaller Q"
    hann = np.clip(q(np.hanning(WIN), 1 << 15), 0, Q15)
    k = np.arange(NFFT // 2)
    cos_t = np.clip(q(np.cos(2 * np.pi * k / NFFT), 1 << 31), -Q31, Q31)
    sin_t = np.clip(q(-np.sin(2 * np.pi * k / NFFT), 1 << 31), -Q31, Q31)   # e^{-j...}
    log2_t = q(np.log2(1 + np.arange(2**LOG2_TABLE_BITS + 1) / 2**LOG2_TABLE_BITS), Q16)

    (out / "hr_tables.h").write_text(f"""/* GENERATED by python/scripts/gen_firmware_tables.py: do not edit. */
#ifndef HR_TABLES_H
#define HR_TABLES_H
#include <stdint.h>

#define HR_BP_SECTIONS   {len(sos)}
#define HR_BP_COEF_Q     29
#define HR_WIN           {WIN}
#define HR_NFFT          {NFFT}
#define HR_LOG2_TBL_BITS {LOG2_TABLE_BITS}

extern const int32_t hr_bp_coef[HR_BP_SECTIONS * 5];   /* b0 b1 b2 a1 a2, Q29 */
extern const int16_t hr_hann_q15[HR_WIN];
extern const int32_t hr_twiddle_cos_q31[HR_NFFT / 2];
extern const int32_t hr_twiddle_sin_q31[HR_NFFT / 2];
extern const int32_t hr_log2_tbl_q16[(1 << HR_LOG2_TBL_BITS) + 1];

#endif
""")
    (out / "hr_tables.c").write_text(
        "/* GENERATED by python/scripts/gen_firmware_tables.py: do not edit. */\n"
        '#include "hr_tables.h"\n\n'
        + c_array("int32_t", "hr_bp_coef", coef, 5) + "\n"
        + c_array("int16_t", "hr_hann_q15", hann, 12) + "\n"
        + c_array("int32_t", "hr_twiddle_cos_q31", cos_t, 6) + "\n"
        + c_array("int32_t", "hr_twiddle_sin_q31", sin_t, 6) + "\n"
        + c_array("int32_t", "hr_log2_tbl_q16", log2_t, 8))
    print(f"wrote {out}/hr_tables.[ch]")


if __name__ == "__main__":
    main()
